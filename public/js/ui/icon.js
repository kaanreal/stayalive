const paths = {}
function path (name) {
  if (paths[name]) return paths[name]
  const rows = art[name] || art.info
  let d = ''
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== '#') continue
      let end = x
      while (row[end + 1] === '#') end++
      d += `M${x} ${y}h${end - x + 1}v1h${x - end - 1}z`
      x = end
    }
  })
  return (paths[name] = d)
}

export function Icon ({ name, label, size, class: className }) {
  return html`<svg class=${cx('icon', size && `icon--${size}`, className)} viewBox="0 0 9 9" role=${label ? 'img' : null} aria-label=${label || null} aria-hidden=${label ? null : 'true'} focusable="false"><path d=${path(name)} /></svg>`
}
